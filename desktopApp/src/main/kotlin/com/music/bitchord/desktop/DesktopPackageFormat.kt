package com.music.bitchord.desktop

import java.io.File

/**
 * Detects the distribution and packaging format of the desktop application.
 */
internal object DesktopPackageFormat {
    const val FORMAT_DEB = "deb"
    const val FORMAT_APPIMAGE = "appimage"

    /**
     * Resolves the packaging format. Returns "deb" for Debian/Ubuntu package installs,
     * "appimage" for Linux AppImages, or an empty string for unpacked/portable builds.
     */
    val current: String by lazy {
        // 1. Explicit JVM property injected at package build time or launcher
        val explicit = System.getProperty("bitchord.package.format")?.trim()?.lowercase()
        if (!explicit.isNullOrEmpty()) return@lazy explicit

        if (System.getProperty("bitchord.deb")?.trim()?.equals("true", ignoreCase = true) == true) {
            return@lazy FORMAT_DEB
        }

        // 2. Linux runtime detection
        if (DesktopPlatform.isLinux) {
            // AppImages export APPIMAGE or APPDIR into environment
            val isAppImage = !System.getenv("APPIMAGE").isNullOrBlank() || !System.getenv("APPDIR").isNullOrBlank()
            if (isAppImage) return@lazy FORMAT_APPIMAGE

            // DEB packages generated by jpackage are installed under /opt/bitchord or /opt/BitChord
            val javaHome = System.getProperty("java.home").orEmpty()
            val appPath = System.getProperty("jpackage.app-path").orEmpty()
            val inOpt = javaHome.contains("/opt/bitchord", ignoreCase = true) ||
                appPath.contains("/opt/bitchord", ignoreCase = true)

            val dpkgFileExists = File("/var/lib/dpkg/info/bitchord.list").isFile ||
                File("/var/lib/dpkg/info/BitChord.list").isFile

            if (inOpt || dpkgFileExists) {
                return@lazy FORMAT_DEB
            }
        }

        ""
    }

    val isDeb: Boolean get() = current == FORMAT_DEB
}
